# ---- Reproducibility -------------------------------------------------------
RANDOM_SEED = 42

# ---- Modelling population --------------------------------------------------
# Only 36-month, Individual loans with a final outcome, issued from 2013.
# - 60-month loans are only partly resolved (83% for 2014, 67% for 2015, less after), which
#   biases their default rate.
# - Joint applications start in 2015, and annual_inc / dti mean something else on them.
# - Bureau-snapshot columns are empty for 2007-2011 and half empty for 2012.
# The excluded loans stay available for EDA. See docs/cleaning_log.md.
MODEL_TERM_MONTHS = 36
MODEL_APPLICATION_TYPE = "Individual"

# ---- Out-of-time split (by issue month) ------------------------------------
# Train on older loans, tune on the next six months, score the final six months once.
# Each set is [start, end): a loan belongs to the set whose start it is on or after.
# All three are fully matured 36-month loans (a December 2015 loan ends in December 2018,
# the end of the data), so their default rates are comparable.
TRAIN_START = date(2013, 1, 1)
VALIDATION_START = date(2015, 1, 1)
TEST_START = date(2015, 7, 1)
TEST_END = date(2016, 1, 1)  # loans issued from here on are excluded: too many unresolved

